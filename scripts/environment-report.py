#!/usr/bin/env python3
"""Write docs/environment.md from what kickoff already collected, without any AI.

Sources: .local/ansible-inventory.json (nodes and groups), .local/inspection/<node>.json
(OS, kernel, CPU, memory, middleware versions), .local/initial-build/environment.txt
(the Rust toolchain on the source node) and .local/progress.log (milestones since kickoff
started). kickoff runs it after the inspection; rerun it after the baseline to extend the
timeline. A file that no longer starts with the generated marker was edited by hand and
is left alone; the report then goes to .local/environment-report.md.
"""
import importlib.util
import json
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parent.parent
MARKER = '<!-- generated by scripts/environment-report.py; delete this line before editing by hand -->'
TOOLS = ['nginx', 'mysql', 'psql', 'redis-server', 'go', 'rustc', 'node', 'ruby', 'python3', 'java']

_spec = importlib.util.spec_from_file_location('progress', Path(__file__).resolve().parent / 'progress.py')
progress = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(progress)


def load(path, default):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return default


def cell(value):
    return str(value if value not in (None, '') else '-').replace('|', '\\|').replace('\n', ' ')


def table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '| ' + ' | '.join('---' for _ in header) + ' |']
    lines += ['| ' + ' | '.join(cell(v) for v in row) + ' |' for row in rows]
    return lines


def groups_of(inventory):
    groups = {}
    for group, entry in inventory.get('all', {}).get('children', {}).items():
        for host in (entry or {}).get('hosts', {}):
            groups.setdefault(host, []).append(group)
    return groups


def timeline(path):
    rows = []
    try:
        lines = Path(path).read_text().splitlines()
    except OSError:
        return rows
    start = None
    for line in lines:
        parts = line.split('\t')
        if len(parts) < 3:
            continue
        try:
            at = time.mktime(time.strptime(parts[0][:19], '%Y-%m-%dT%H:%M:%S'))
        except ValueError:
            continue
        if parts[1] == 'kickoff' and parts[2] == 'started':
            start, rows = at, []  # the latest kickoff run is the one that counts
        if start is None:
            continue
        elapsed = int(at - start)
        rows.append((parts[0][11:19], f'{elapsed // 60}:{elapsed % 60:02d}', parts[1], parts[2],
                     parts[3] if len(parts) > 3 else ''))
    return rows


def report():
    inventory = load(ROOT / '.local/ansible-inventory.json', {})
    groups = groups_of(inventory)
    inspections = {p.stem: load(p, {}) for p in sorted((ROOT / '.local/inspection').glob('*.json'))}
    nodes = sorted(set(groups) | set(inspections))
    out = [MARKER, '# 環境', '',
           f'{time.strftime("%Y-%m-%d %H:%M:%S")}に、kickoffが集めた調査結果から機械的に作った。'
           '値はinspection時点のもの。確かめたらcommitし、補足は手で書き足す（そのときは1行目を消す）。', '',
           '## 台数とrole', '', f'{len(nodes)}台。roleはinventoryのgroup（draft反映後は`role_*`も入る）。', '']
    out += table(['node', 'group'], [(n, ', '.join(sorted(groups.get(n, [])))) for n in nodes])
    out += ['', '## サーバー', '']
    out += table(['node', 'OS', 'kernel', 'arch', 'vCPU', 'memory'],
                 [(n, f'{i.get("distribution", "")} {i.get("distribution_version", "")}'.strip(), i.get('kernel'),
                   i.get('architecture'), i.get('processor_vcpus'),
                   f'{i["memory_mb"]} MB' if i.get('memory_mb') else None)
                  for n, i in inspections.items()])
    found = [t for t in TOOLS if any((i.get('versions') or {}).get(t) for i in inspections.values())]
    out += ['', '## ミドルウェアと言語の版', '', 'inspectionのuserのPATHで見つかったもの。見つからないものは`-`。', '']
    out += table(['node', *found], [(n, *[(i.get('versions') or {}).get(t) for t in found]) for n, i in inspections.items()])
    environment = ROOT / '.local/initial-build/environment.txt'
    out += ['', '## 配布サーバーのRust（初期build処理の調査、isucon user）', '']
    if environment.exists():
        lines = [line for line in environment.read_text().splitlines()
                 if line.startswith(('rustc ', 'cargo ', 'glibc ', 'OpenSSL ', 'PRETTY_NAME=')) or line.endswith('/rustc')]
        out += ['```text', *(lines or ['(rustc not found)']), '```']
    else:
        out += ['未取得（`.local/initial-build/environment.txt`がない）']
    rows = timeline(progress.log_path(ROOT))
    out += ['', '## 開始からの計時', '',
            '開始宣言の時刻: （人間が記入）。経過はkickoffの開始から。`.local/progress.log`の行をそのまま並べた。', '']
    out += table(['時刻', 'kickoffから', '出どころ', '状態', '内容'], rows) if rows else ['progress.logに行がない']
    return '\n'.join(out) + '\n'


def main():
    target = ROOT / 'docs/environment.md'
    text = report()
    if target.exists() and not target.read_text().startswith(MARKER):
        target = ROOT / '.local/environment-report.md'
        print('docs/environment.md was edited by hand; wrote the new report beside it', file=sys.stderr)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    print(f'environment report: {target.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
