#!/usr/bin/env bash
set -euo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
repo_dir=$(cd -- "${script_dir}/.." && pwd)
inventory_path=${ANSIBLE_INVENTORY:-${repo_dir}/.local/ansible-inventory.json}
node_name=${1:-}
remote_command=${2:-}

test -n "${node_name}" && test -n "${remote_command}" || {
  echo "usage: $0 NODE 'REMOTE COMMAND'" >&2
  exit 2
}
command -v jq >/dev/null
command -v ssh >/dev/null
test -f "${inventory_path}" || { echo "run make discover first" >&2; exit 1; }

node=$(jq -ce --arg name "${node_name}" '
  .all as $all |
  [$all.children[].hosts | to_entries[] | select(.key == $name) |
    .value + {name: .key, default_user: $all.vars.ansible_user,
      identity_file: $all.vars.ansible_ssh_private_key_file,
      common_args: $all.vars.ansible_ssh_common_args}] | first
' "${inventory_path}") || {
  echo "unknown node: ${node_name}" >&2
  exit 1
}

# ベンチnodeにはベンチadapterとkickoffの検査だけが入る。練習の規則（ベンチnodeを観測しない、
# ベンチマーカーを写さない）を、hookで見えないscript経由の接続でも守るため、ここでも断る。
# BENCHMARK_NODE_ACCESS=none（既定）なら、ベンチadapterからも接続しない（本番では運営の台）。
if jq -e --arg name "${node_name}" '.all.children.benchmark.hosts // {} | has($name)' "${inventory_path}" >/dev/null; then
  if [[ "$(jq -r '.all.vars.isucon_benchmark_node_access // "none"' "${inventory_path}")" != ssh ]]; then
    echo "refusing to connect to the benchmark node ${node_name}: BENCHMARK_NODE_ACCESS is none; set it to ssh in .local/environment.env and rerun make discover only when the practice runs its benchmark over SSH" >&2
    exit 1
  fi
  if [[ "${ISUCON_ALLOW_BENCHMARK_NODE:-}" != 1 ]]; then
    echo "refusing to connect to the benchmark node ${node_name}: run benchmarks through isuscope run (.isuscope/benchmark.sh)" >&2
    exit 1
  fi
fi

host=$(jq -r '.ansible_host' <<<"${node}")
user=$(jq -r '.ansible_user // .default_user' <<<"${node}")
identity_file=$(jq -r '.identity_file' <<<"${node}")
common_args=$(jq -r '.common_args' <<<"${node}")
case "${identity_file}" in /*) ;; *) identity_file=${repo_dir}/${identity_file} ;; esac
test -f "${identity_file}" || { echo "missing SSH identity: ${identity_file}" >&2; exit 1; }

# common_args is generated by this repository, not accepted from benchmark output.
# shellcheck disable=SC2206
ssh_options=(${common_args})
# A node that stops answering after the session is up (out of memory, overloaded) ends the session
# in about 15 seconds instead of hanging; ConnectTimeout in common_args covers the connection.
ssh_options+=(-o ServerAliveInterval=5 -o ServerAliveCountMax=3)
# Reuse one connection per node: deploy, prepare and the checks open many short sessions,
# each paying a full handshake otherwise. The socket path stays short for macOS (104 bytes).
# SSH_CONTROL_PERSIST=0 turns it off.
persist=${SSH_CONTROL_PERSIST:-60}
if [[ "${persist}" != 0 ]]; then
  control_dir=/tmp/isucon-ssh-$(id -u)
  if mkdir -p -m 0700 "${control_dir}" 2>/dev/null && [[ -O "${control_dir}" ]]; then
    ssh_options+=(-o ControlMaster=auto -o "ControlPath=${control_dir}/%C" -o "ControlPersist=${persist}")
  fi
fi
exec ssh -i "${identity_file}" "${ssh_options[@]}" "${user}@${host}" "${remote_command}"
